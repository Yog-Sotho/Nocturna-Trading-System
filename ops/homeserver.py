def check_stack(m: Machine, env_file: Path) -> None:
    area = "Stack"
    if not (m.docker and m.compose and env_file.exists()):
        return
    config = m.run(["docker", "compose", "config", "--quiet"])
    if config.code != 0:
        m.add("fix", area, f"docker compose rejects the configuration: {_first_line(config.err)}", STEP_ENV)
        return
    if m.run(["docker", "image", "inspect", IMAGE]).code == 0:
        verdict = m.run(["docker", "compose", "run", "--rm", "--no-deps", "-T", "api", "python", "-c",
                         _SETTINGS_CHECK])
        if verdict.code == 0:
            m.add("ok", area, "the app accepts this configuration")
        else:
            for line in (verdict.out.strip() or _first_line(verdict.err)).splitlines():
                m.add("fix", area, f"the app refuses the configuration: {line.strip()}", STEP_ENV)
    else:
        m.add("info", area, "the image is not built yet (docker compose up -d --build)")
    listed = m.run(["docker", "compose", "ps", "--all", "--format", "json"])
    services = []
    text = listed.out.strip()
    if listed.code == 0 and text:
        try:
            parsed = json.loads(text)
            services = parsed if isinstance(parsed, list) else [parsed]
        except ValueError:
            for line in text.splitlines():
                try:
                    services.append(json.loads(line))
                except ValueError:
                    continue
    if not services:
        m.add("info", area, "not started yet", STEP_START)
        return
    for service in services:
        name, state, health = service.get("Service", "?"), service.get("State", "?"), service.get("Health", "")
        if state == "running" and health in ("", "healthy"):
            m.add("ok", area, f"{name}: running{', healthy' if health else ''}")
        elif state == "running" and health == "starting":
            m.add("info", area, f"{name}: starting")
        else:
            m.add("fix", area, f"{name}: {state}{', ' + health if health else ''} "
                               f"(docker compose logs {name})", STEP_START)
    dumps = sorted((m.root / "backups").glob("nocturna-*.dump"))
    if dumps:
        age = (datetime.now().timestamp() - dumps[-1].stat().st_mtime) / 3600
        m.add("ok" if age < 26 else "warn", area, f"newest backup {age:.0f} hours old ({len(dumps)} kept)")


def check(m: Machine, env_file: Path) -> list[Finding]:
    check_system(m)
    check_tools(m)
    check_docker(m)
    check_tailscale(m)
    check_repo(m)
    check_env(m, env_file)
    check_port(m)
    check_stack(m, env_file)
    for finding in m.findings:
        for value in sorted(m.hide, key=len, reverse=True):
            finding.text = finding.text.replace(value, "***")
    return m.findings


_MARK = {"ok": "ok  ", "info": "    ", "warn": "WARN", "fix": "FIX "}


def report(findings: list[Finding]) -> str:
    lines = ["Nocturna home server check: it changes nothing (testing the settings starts one throwaway",
             "container) and shows no secrets, so you can share this report.", ""]
    area = None
    for f in findings:
        if f.area != area:
            area = f.area
            lines.append(area)
        step = f"  [step {f.step}]" if f.step and f.level in ("warn", "fix") else ""
        lines.append(f"  {_MARK[f.level]}  {f.text}{step}")
    todo = [f for f in findings if f.level in ("fix", "warn")]
    lines.append("")
    if todo:
        lines.append(f"To do, in the order of {GUIDE}:")
        for n, f in enumerate(sorted(todo, key=lambda f: (f.step or 99, f.level != "fix")), start=1):
            where = f"step {f.step}: " if f.step else ""
            lines.append(f"  {n}. {_MARK[f.level].strip()} {where}{f.text}")
    if not any(f.level == "fix" for f in findings):
        lines.append("Nothing to fix." + (" Read the warnings above." if todo else ""))
    return "\n".join(lines)


