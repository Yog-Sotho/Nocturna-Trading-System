_PLACEHOLDER = re.compile(r"your-|yourdomain|example\.com|<|>|changeme", re.IGNORECASE)
_URL_SAFE = re.compile(r"[A-Za-z0-9]+")
_TOKEN = re.compile(r"\d+:[A-Za-z0-9_-]{20,}")
_CHAT = re.compile(r"-?\d+")
_ORIGIN = re.compile(r"https?://[^/\s,]+")


def is_placeholder(value: str) -> bool:
    return bool(_PLACEHOLDER.search(value))


_SECRET_NAME = re.compile(r"KEY|SECRET|TOKEN|PASSWORD|PEPPER|HEARTBEAT|NTFY|WEBHOOK|DATABASE_URL|REDIS_URL")


def secret_values(values: dict[str, str]) -> set[str]:
    """The values never to show: secrets, and URLs that work as one (a ping URL, an ntfy topic)."""
    return {value for name, value in values.items() if _SECRET_NAME.search(name) and len(value) >= 4}


def env_problems(values: dict[str, str]) -> dict[str, tuple[str, str]]:
    """Problems per setting: name -> (fix or warn, message). Messages never contain the value."""
    found: dict[str, tuple[str, str]] = {}

    def fix(name: str, message: str) -> None:
        found[name] = ("fix", message)

    def warn(name: str, message: str) -> None:
        found.setdefault(name, ("warn", message))

    for var in VARS:
        value = values.get(var.name, "").strip()
        if not value:
            if var.need == "required" and var.name not in ("ENGINE_AUTOSTART", "TRUSTED_PROXY_COUNT"):
                fix(var.name, "missing")
            elif var.need == "recommended" and var.name != "TELEGRAM_COMMANDS":
                warn(var.name, "not set")
        elif is_placeholder(value):
            fix(var.name, "still the example value")
    for name in ("FLASK_SECRET_KEY", "JWT_SECRET_KEY", "API_KEY_PEPPER"):
        if name not in found and len(values[name]) < 32:
            fix(name, "shorter than 32 characters")
    if "JWT_SECRET_KEY" not in found and values["JWT_SECRET_KEY"] == values.get("FLASK_SECRET_KEY"):
        fix("JWT_SECRET_KEY", "the same as FLASK_SECRET_KEY")
    for name in ("DB_PASSWORD", "REDIS_PASSWORD"):
        if name not in found and not _URL_SAFE.fullmatch(values[name]):
            fix(name, "use letters and digits only: it goes into a URL")
    key = values.get("ALPACA_API_KEY", "")
    if "ALPACA_API_KEY" not in found and not key.upper().startswith("PK"):
        warn("ALPACA_API_KEY", "paper Key IDs start with PK: is this a live key?")
    if "ALLOWED_ORIGINS" not in found:
        origins = [o.strip() for o in values["ALLOWED_ORIGINS"].split(",") if o.strip()]
        if not origins or not all(_ORIGIN.fullmatch(o) for o in origins):
            fix("ALLOWED_ORIGINS", "not an address like https://name.tailnet.ts.net (no path, no trailing /)")
    proxies = values.get("TRUSTED_PROXY_COUNT", "").strip()
    if proxies != "1":
        warn("TRUSTED_PROXY_COUNT", "should be 1 behind Tailscale Serve, or every visitor looks the same "
                                    "and a few failed logins lock everyone out")
    token, chat = values.get("ALERT_TELEGRAM_BOT_TOKEN", "").strip(), values.get("ALERT_TELEGRAM_CHAT_ID", "").strip()
    if token and "ALERT_TELEGRAM_BOT_TOKEN" not in found and not _TOKEN.fullmatch(token):
        fix("ALERT_TELEGRAM_BOT_TOKEN", "not a bot token (digits, a colon, then letters and digits)")
    if chat and "ALERT_TELEGRAM_CHAT_ID" not in found and not _CHAT.fullmatch(chat):
        fix("ALERT_TELEGRAM_CHAT_ID", "not a chat id (a number)")
    if bool(token) != bool(chat):
        fix("ALERT_TELEGRAM_CHAT_ID" if token else "ALERT_TELEGRAM_BOT_TOKEN",
            "set the bot token and the chat id together, or neither")
    commands = values.get("TELEGRAM_COMMANDS", "").strip().lower()
    if commands not in ("", "true", "false"):
        fix("TELEGRAM_COMMANDS", "must be true or false")
    elif commands == "true" and not (token and chat):
        fix("TELEGRAM_COMMANDS", "needs the bot token and the chat id")
    for name in ("HEARTBEAT_URL", "BACKUP_HEARTBEAT_URL"):
        url = values.get(name, "").strip()
        if url and name not in found:
            if not url.startswith("https://"):
                fix(name, "must start with https://")
            elif not url.startswith("https://hc-ping.com/"):
                warn(name, "healthchecks.io ping URLs start with https://hc-ping.com/")
    if values.get("HEARTBEAT_URL") and values.get("HEARTBEAT_URL") == values.get("BACKUP_HEARTBEAT_URL"):
        fix("BACKUP_HEARTBEAT_URL", "the same as HEARTBEAT_URL: give each its own check")
    autostart = values.get("ENGINE_AUTOSTART", "").strip().lower()
    if autostart not in ("", "true", "false"):
        fix("ENGINE_AUTOSTART", "must be true or false")
    elif autostart == "true":
        warn("ENGINE_AUTOSTART", "true: trading restarts by itself after a crash or a reboot")
    return found


# -- what is on the machine -----------------------------------------------------------------

@dataclass
class Finding:
    level: str  # ok, warn, fix, info
    area: str
    text: str
    step: int | None = None


@dataclass
class Machine:
    """What `check` learned, shared between its parts."""

    run: Runner
    http: Http
    root: Path = ROOT
    listening: Callable[[int], bool] = lambda port: _listening(port)
    docker: bool = False  # the daemon answers this user
    compose: bool = False
    tailscale_origin: str | None = None
    serving: bool | None = None  # Tailscale Serve forwards to the API (None: unknown)
    findings: list[Finding] = field(default_factory=list)
    hide: set[str] = field(default_factory=set)  # .env values, scrubbed from every message

    def add(self, level: str, area: str, text: str, step: int | None = None) -> None:
        self.findings.append(Finding(level, area, text, step))


def _first_line(text: str) -> str:
    lines = [line.strip() for line in text.strip().splitlines() if line.strip()]
    return lines[0] if lines else ""


def check_system(m: Machine, os_release: Path = Path("/etc/os-release"),
                 meminfo: Path = Path("/proc/meminfo"), batteries: Path = Path("/sys/class/power_supply")) -> None:
    area = "System"
    info = {}
    if os_release.exists():
        for name, value, _ in parse_env(os_release.read_text()):
            info[name] = value
    name = info.get("PRETTY_NAME", platform.system())
    codename = info.get("UBUNTU_CODENAME") or info.get("VERSION_CODENAME", "")
    memory = disk = ""
    if meminfo.exists():
        kb = re.search(r"MemTotal:\s+(\d+)", meminfo.read_text())
        if kb:
            gb = int(kb.group(1)) / 1024 ** 2
            memory = f", {gb:.1f} GB RAM"
            if gb < 2:
                m.add("warn", area, f"{gb:.1f} GB RAM: building the image and running the stack may run out")
    free = shutil.disk_usage(m.root).free / 1024 ** 3
    disk = f", {free:.0f} GB free"
    m.add("info", area, f"{name}{f' ({codename})' if codename else ''}, {platform.machine()}, "
                        f"{os.cpu_count()} CPUs{memory}{disk}")
    if info.get("ID", "").lower() != "ubuntu":
        m.add("warn", area, "not Ubuntu: the guide's install commands are for Ubuntu")
    if free < 5:
        m.add("warn", area, f"{free:.1f} GB free disk: the image and the backups need more")

    synced = m.run(["timedatectl", "show", "-p", "NTPSynchronized", "--value"])
    if synced.code == 0 and synced.out.strip() == "yes":
        m.add("ok", area, "clock synchronized")
    elif synced.code == 0:
        m.add("fix", area, "clock not synchronized: sign-ins and market times depend on it", STEP_MACHINE)
    else:
        m.add("info", area, "could not read the clock state (timedatectl)")

    if batteries.exists() and any(p.name.startswith("BAT") for p in batteries.iterdir()):
        logind = m.run(["systemd-analyze", "cat-config", "systemd/logind.conf"])
        settings = dict(re.findall(r"^\s*(HandleLidSwitch(?:ExternalPower)?)\s*=\s*(\S+)", logind.out, re.M))
        if settings.get("HandleLidSwitch") == "ignore" and settings.get("HandleLidSwitchExternalPower",
                                                                          "ignore") == "ignore":
            m.add("ok", area, "laptop: closing the lid does not suspend it")
        else:
            m.add("warn", area, "laptop: closing the lid suspends it, and the stack with it", STEP_MACHINE)


def check_tools(m: Machine) -> None:
    for program, why, level in (("git", "needed to get and update the code", "fix"),
                                ("curl", "used by the Docker and Tailscale install commands", "warn")):
        found = m.run([program, "--version"])
        if found.code == 0:
            words = _first_line(found.out).split()
            m.add("ok", "Tools", " ".join(words[:3] if program == "git" else words[:2]))
        else:
            m.add(level, "Tools", f"{program} is not installed ({why}): sudo apt install {program}", STEP_MACHINE)


def check_docker(m: Machine) -> None:
    area = "Docker"
    client = m.run(["docker", "--version"])
    if client.code != 0:
        m.add("fix", area, "Docker is not installed", STEP_DOCKER)
        return
    m.add("ok", area, _first_line(client.out))
    if m.run(["snap", "list", "docker"]).code == 0:
        m.add("warn", area, "Docker comes from the snap store; the guide uses Docker's apt packages. If the "
                            "stack cannot write ./backups, switch (step 3)", STEP_DOCKER)
    elif m.run(["dpkg-query", "-W", "-f=${Status}", "docker.io"]).out.startswith("install ok"):
        m.add("info", area, "Docker is Ubuntu's docker.io package (works; the guide installs Docker's own)")
    server = m.run(["docker", "info", "--format", "{{.ServerVersion}}"])
    if server.code == 0:
        m.docker = True
        m.add("ok", area, f"Docker Engine {server.out.strip()} answers this user")
    elif "permission denied" in server.err.lower():
        m.add("fix", area, "your user cannot use Docker: sudo usermod -aG docker $USER, then log in again",
              STEP_DOCKER)
    else:
        m.add("fix", area, "Docker is installed but not running: sudo systemctl enable --now docker", STEP_DOCKER)
    enabled = m.run(["systemctl", "is-enabled", "docker"])
    if enabled.code == 0 and enabled.out.strip() == "enabled":
        m.add("ok", area, "Docker starts at boot")
    elif enabled.code != 127 and enabled.out.strip():
        m.add("fix", area, f"Docker does not start at boot ({enabled.out.strip()}): sudo systemctl enable docker",
              STEP_DOCKER)
    compose = m.run(["docker", "compose", "version", "--short"])
    version = compose.out.strip().lstrip("v")
    if compose.code == 0 and version.split(".")[0].isdigit() and int(version.split(".")[0]) >= 2:
        m.compose = True
        m.add("ok", area, f"Docker Compose {version}")
    else:
        m.add("fix", area, "the Docker Compose v2 plugin is missing: sudo apt install docker-compose-plugin "
                           "(docker-compose-v2 with Ubuntu's docker.io)", STEP_DOCKER)


def check_tailscale(m: Machine) -> None:
    area = "Tailscale"
    version = m.run(["tailscale", "version"])
    if version.code != 0:
        m.add("fix", area, "Tailscale is not installed", STEP_TAILSCALE)
        return
    m.add("ok", area, f"Tailscale {_first_line(version.out)}")
    status = m.run(["tailscale", "status", "--json"])
    try:
        state = json.loads(status.out) if status.out.strip() else {}
    except ValueError:
        state = {}
    backend = state.get("BackendState", "")
    if not backend and "tailscaled" in status.err:
        m.add("fix", area, "the Tailscale service is not running: sudo systemctl enable --now tailscaled",
              STEP_TAILSCALE)
        return
    if backend != "Running":
        m.add("fix", area, f"not connected ({backend or 'no status'}): sudo tailscale up", STEP_TAILSCALE)
        return
    me = state.get("Self") or {}
    name = (me.get("DNSName") or "").rstrip(".")
    tailnet = state.get("CurrentTailnet") or {}
    if not tailnet.get("MagicDNSEnabled"):
        m.add("fix", area, "MagicDNS is off: turn it on in the admin console, DNS page", STEP_TAILSCALE)
    if not state.get("CertDomains"):
        m.add("fix", area, "HTTPS certificates are off: enable them in the admin console, DNS page", STEP_TAILSCALE)
    if name:
        m.tailscale_origin = f"https://{name}"
        m.add("ok", area, f"connected as {name}")
    if me.get("KeyExpiry"):
        m.add("warn", area, f"this machine's key expires ({me['KeyExpiry'][:10]}): disable key expiry for it "
                            "on the Machines page, or it drops off your tailnet", STEP_TAILSCALE)
    serve = m.run(["tailscale", "serve", "status", "--json"])
    if serve.code != 0:
        m.add("info", area, "could not read what Tailscale serves: run `sudo tailscale serve status`")
        return
    try:
        config = json.loads(serve.out) if serve.out.strip() else {}
    except ValueError:
        config = {}
    proxies = [handler.get("Proxy", "") for site in (config.get("Web") or {}).values()
               for handler in ((site or {}).get("Handlers") or {}).values() if isinstance(handler, dict)]
    m.serving = any(re.search(rf"(^|[/:]){API_PORT}/?$", proxy) for proxy in proxies)
    if m.serving:
        m.add("ok", area, f"serves the dashboard at {m.tailscale_origin or 'your tailnet address'}")
    else:
        m.add("fix", area, f"does not serve the dashboard yet: sudo tailscale serve --bg {API_PORT}", STEP_TAILSCALE)


def check_repo(m: Machine) -> None:
    head = m.run(["git", "-C", str(m.root), "log", "-1", "--format=%h %cs %s"])
    if head.code == 0:
        m.add("info", "Code", f"{m.root} at {head.out.strip()}")
    changed = m.run(["git", "-C", str(m.root), "status", "--porcelain", "--untracked-files=no"])
    if changed.code == 0 and changed.out.strip():
        m.add("warn", "Code", "files of the repository were changed here: `git pull` may refuse to update")


def _listening(port: int) -> bool:
    with socket.socket() as probe:
        probe.settimeout(1)
        return probe.connect_ex(("127.0.0.1", port)) == 0


def check_port(m: Machine) -> None:
    if not m.listening(API_PORT):
        m.add("info", "Stack", f"nothing listens on port {API_PORT} yet")
        return
    answer = m.http("GET", f"http://127.0.0.1:{API_PORT}/health", timeout=5)
    if answer.status == 200 and b"healthy" in answer.body:
        m.add("ok", "Stack", f"the Nocturna API answers on 127.0.0.1:{API_PORT}")
    else:
        m.add("fix", "Stack", f"another program uses port {API_PORT}: the API cannot start", STEP_START)


def _project(root: Path) -> str:
    """Compose's default project name: the folder's name, lower case, a-z 0-9 - _ only."""
    return re.sub(r"[^a-z0-9_-]", "", root.name.lower())


def postgres_volume_exists(m: Machine) -> bool:
    found = m.run(["docker", "volume", "ls", "-q", "--filter", f"label=com.docker.compose.project={_project(m.root)}",
                   "--filter", "label=com.docker.compose.volume=postgres-data"])
    return found.code == 0 and bool(found.out.strip())


def check_env(m: Machine, path: Path) -> dict[str, str]:
    area = ".env"
    if not path.exists():
        m.add("fix", area, "there is no .env yet: python3 ops/homeserver.py env", STEP_ENV)
        if m.docker and postgres_volume_exists(m):
            m.add("fix", area, "the database already exists: .env needs the DB_PASSWORD it was created with",
                  STEP_ENV)
        return {}
    mode = path.stat().st_mode & 0o777
    if mode & 0o077:
        m.add("warn", area, f"readable by other users (mode {mode:o}): chmod 600 .env", STEP_ENV)
    values = env_values(path)
    m.hide.update(secret_values(values))
    problems = env_problems(values)
    for var in VARS:
        if var.name in problems:
            level, message = problems[var.name]
            m.add(level, area, f"{var.name}: {message}", STEP_ACCOUNTS if var.name.startswith(
                ("ALPACA", "ALERT", "HEARTBEAT", "BACKUP")) else STEP_ENV)
        elif values.get(var.name, "").strip():
            m.add("ok", area, f"{var.name}: set")
    if m.tailscale_origin and "ALLOWED_ORIGINS" not in problems:
        origins = [o.strip() for o in values["ALLOWED_ORIGINS"].split(",")]
        if m.tailscale_origin not in origins:
            m.add("fix", area, f"ALLOWED_ORIGINS does not list this machine's address, {m.tailscale_origin}",
                  STEP_ENV)
    ignored = [name for name in STACK_SETS if name in values]
    if ignored:
        m.add("info", area, f"ignored, the stack sets them itself: {', '.join(ignored)}")
    bind = values.get("API_BIND", "").strip()
    if bind and bind not in ("127.0.0.1", "localhost"):
        m.add("warn", area, f"API_BIND={bind} opens the API to your network without HTTPS; Tailscale does not "
                            "need it: remove the line", STEP_ENV)
    return values


