def write_env(env_file: Path, values: dict[str, str], previous: list[tuple[str, str, str]]) -> None:
    """Write .env (mode 600, replaced in one step), after copying the old one aside."""
    known = {name for _, names in _SECTIONS for name in names}
    lines = [f"# Nocturna home server settings, written by ops/homeserver.py on {datetime.now():%Y-%m-%d %H:%M}.",
             f"# {GUIDE} explains each one. Keep this file private; run `python3 ops/homeserver.py env`",
             "# again to change it."]
    for title, names in _SECTIONS:
        lines += ["", f"# {title}"]
        lines += [env_line(name, values.get(name, "")) for name in names]
    kept = [raw for name, value, raw in previous
            if name not in known and name not in STACK_SETS and not is_placeholder(value)]
    if kept:
        lines += ["", "# Kept from the previous .env"] + kept
    if env_file.exists():
        backup = env_file.with_name(f".env.backup-{datetime.now():%Y%m%d-%H%M%S}")
        _write_private(backup, env_file.read_text())
    _write_private(env_file, "\n".join(lines) + "\n")


def _write_private(path: Path, text: str) -> None:
    temporary = path.with_name(path.name + ".tmp")
    temporary.unlink(missing_ok=True)
    descriptor = os.open(temporary, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
    with os.fdopen(descriptor, "w") as handle:
        handle.write(text)
    os.replace(temporary, path)


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Check the home server, or build its .env (docs/HOME_SERVER.md).")
    parser.add_argument("command", choices=("check", "env"))
    parser.add_argument("--env-file", type=Path, default=ROOT / ".env", help=argparse.SUPPRESS)
    args = parser.parse_args(argv)
    if args.command == "check":
        findings = check(Machine(run, http), args.env_file)
        print(report(findings))
        return 1 if any(f.level == "fix" for f in findings) else 0
    try:
        return build_env(args.env_file, run, http, Dialog())
    except (KeyboardInterrupt, EOFError):
        print("\nStopped; .env was not changed.")
        return 130


if __name__ == "__main__":
    sys.exit(main())
